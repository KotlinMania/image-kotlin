    @Test
    fun icoRoundTripRgba() {
        val width = 4u
        val height = 4u
        val pixels = ByteArray((width * height * 4u).toInt())
        for (i in pixels.indices) {
            pixels[i] = (i * 17).toByte()
        }

        val out = BufferIoWrite()
        val encoder = IcoEncoder(out)
        encoder.writeImage(pixels, width, height, ExtendedColorType.Rgba8)

        val encoded = out.toByteArray()
        assertTrue(encoded.isNotEmpty())

        val decoder = IcoDecoder(BufferIoRead(encoded))
        assertEquals(Pair(width, height), decoder.dimensions())
        assertEquals(ColorType.Rgba8, decoder.colorType())

        val decoded = ByteArray((width * height * 4u).toInt())
        decoder.readImage(decoded)
        for (i in pixels.indices) {
            assertEquals(pixels[i], decoded[i], "Mismatch at byte $i")
        }
    }

    @Test
    fun icoMultiFrameSelection() {
        val frame1Data = ByteArray((4 * 4 * 4)) { 10 }
        val frame1 = IcoFrame.asBmp(frame1Data, 4u, 4u, ExtendedColorType.Rgba8)

        val frame2Data = ByteArray((8 * 8 * 4)) { 20 }
        val frame2 = IcoFrame.asBmp(frame2Data, 8u, 8u, ExtendedColorType.Rgba8)

        val out = BufferIoWrite()
        val encoder = IcoEncoder(out)
        encoder.encodeImages(listOf(frame1, frame2))

        val encoded = out.toByteArray()
        val decoder = IcoDecoder(BufferIoRead(encoded))
        // Should select frame2 as best entry (8x8 > 4x4)
        assertEquals(Pair(8u, 8u), decoder.dimensions())
    }

    @Test
    fun icoInvalidDimensions() {
        assertFailsWith<ImageError.Parameter> {
            IcoFrame.withEncoded(ByteArray(10), 0u, 16u, ExtendedColorType.Rgba8)
        }
        assertFailsWith<ImageError.Parameter> {
            IcoFrame.withEncoded(ByteArray(10), 257u, 16u, ExtendedColorType.Rgba8)
        }
        assertFailsWith<ImageError.Parameter> {
            IcoFrame.withEncoded(ByteArray(10), 16u, 0u, ExtendedColorType.Rgba8)
        }
        assertFailsWith<ImageError.Parameter> {
            IcoFrame.withEncoded(ByteArray(10), 16u, 257u, ExtendedColorType.Rgba8)
        }
    }
